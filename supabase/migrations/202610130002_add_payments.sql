-- Required before deploying Cashfree payment code. Run once through Supabase migrations or SQL Editor.
create table public.payments (
  id bigint generated by default as identity primary key,
  invitation_id bigint not null references public.invitations(id) on delete restrict,
  order_id text not null unique,
  provider text not null default 'cashfree',
  template_id text not null,
  amount numeric(10,2) not null check (amount > 0),
  currency char(3) not null check (currency = 'INR'),
  status text not null check (status in ('created', 'pending', 'paid', 'failed')),
  payment_session_id text,
  cashfree_payment_id text,
  provider_order_status text,
  verification_details jsonb not null default '{}'::jsonb,
  verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.payments enable row level security;

create unique index payments_cashfree_payment_id_unique
  on public.payments(cashfree_payment_id)
  where cashfree_payment_id is not null;

create unique index payments_one_active_order_per_invitation
  on public.payments(invitation_id)
  where status in ('created', 'pending');

create or replace function public.mark_invitation_payment_paid(
  p_order_id text,
  p_invitation_id bigint,
  p_amount numeric,
  p_currency char(3),
  p_cashfree_payment_id text,
  p_provider_order_status text,
  p_verification_details jsonb
) returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  payment_record public.payments%rowtype;
  invitation_status text;
begin
  -- Every caller is additionally verified server-side with Cashfree. These
  -- checks make accidental or replayed RPC calls unable to publish a draft.
  if p_order_id is null
    or p_invitation_id is null
    or p_amount is null
    or p_amount <= 0
    or p_currency is null
    or p_currency <> 'INR'
    or p_cashfree_payment_id is null
    or length(btrim(p_cashfree_payment_id)) = 0
    or p_provider_order_status <> 'PAID'
    or p_verification_details is null
    or jsonb_typeof(p_verification_details) <> 'object' then
    return false;
  end if;

  select * into payment_record
  from public.payments
  where order_id = p_order_id
  for update;

  if not found
    or payment_record.invitation_id <> p_invitation_id
    or payment_record.amount <> p_amount
    or payment_record.currency <> p_currency then
    return false;
  end if;

  -- A retry for the same verified provider payment is safe. A different
  -- provider payment ID must never replace the original settled payment.
  if payment_record.status = 'paid' then
    if payment_record.cashfree_payment_id is distinct from p_cashfree_payment_id then
      return false;
    end if;

    select status into invitation_status
    from public.invitations
    where id = payment_record.invitation_id;
    return invitation_status = 'published';
  end if;

  if payment_record.status not in ('created', 'pending') then
    return false;
  end if;

  select status into invitation_status
  from public.invitations
  where id = payment_record.invitation_id
  for update;

  if not found or invitation_status <> 'draft' then
    return false;
  end if;

  update public.payments
  set status = 'paid',
      cashfree_payment_id = p_cashfree_payment_id,
      provider_order_status = p_provider_order_status,
      verification_details = p_verification_details,
      verified_at = now(),
      updated_at = now()
  where id = payment_record.id;

  update public.invitations
  set status = 'published'
  where id = payment_record.invitation_id
    and status = 'draft';

  return true;
end;
$$;

-- No browser role receives direct access. The server-only Supabase admin
-- client uses service_role for payment rows and this narrowly callable RPC.
revoke all on table public.payments from public, anon, authenticated;
revoke all on sequence public.payments_id_seq from public, anon, authenticated;
grant select, insert, update on table public.payments to service_role;
grant usage, select on sequence public.payments_id_seq to service_role;
revoke all on function public.mark_invitation_payment_paid(text, bigint, numeric, char(3), text, text, jsonb) from public, anon, authenticated;
grant execute on function public.mark_invitation_payment_paid(text, bigint, numeric, char(3), text, text, jsonb) to service_role;
